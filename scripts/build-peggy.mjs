// Precompiles platform proxy-line grammars: Workers forbid runtime code generation (peggy.generate uses `new Function`).
import { readFileSync, writeFileSync } from "node:fs";
import peggy from "peggy";

const dir = new URL("../core/parser/platform/peggy/", import.meta.url);

for (const name of ["loon", "qx", "surge"]) {
  const grammar = readFileSync(new URL(`${name}.pegjs`, dir), "utf8");
  const source = peggy.generate(grammar, { output: "source", format: "es" });
  writeFileSync(new URL(`${name}.generated.js`, dir), `// Generated by scripts/build-peggy.mjs. Do not edit.\n${source}`);
  console.log(`[peggy] ${name}.generated.js`);
}
